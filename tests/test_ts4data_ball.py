class CurveModeTests(unittest.TestCase):
    def test_step_and_ramp(self):
        keys = [[500.0, 3000.0, 80.0, 0.0, 135.0]]
        self.assertEqual(T.eval_curve20(keys, 1750.0), 80.0)
        self.assertEqual(T.eval_curve20(keys, 1750.0, "step"), 80.0)
        self.assertAlmostEqual(T.eval_curve20(keys, 1750.0, "ramp"), 107.5)
        self.assertAlmostEqual(T.eval_curve20(keys, 4000.0, "ramp"), 135.0)
        self.assertEqual(T.eval_value({"type": "curve20", "keys": keys}, 3000.0, 0.0, "ramp"), 135.0)


class NamedRowTests(unittest.TestCase):
    def setUp(self):
        data, row = build()
        self.dec = T.decode_all(data)
        self.row = self.dec["files"][0]["rows"][0]

    def test_named_fields(self):
        n = T.named_row(self.row)
        self.assertEqual(n["header"]["row_type"], "85b71a2b")
        self.assertEqual(n["header"]["aim_key_group"], "FlatReturn")
        self.assertEqual(n["primary"]["keys"][0], {"x0": 500.0, "x1": 3000.0, "y0": 130.0, "slope": 0.0, "y1": 120.0})
        self.assertEqual(n["primary_unit"], "km/h")
        self.assertEqual(n["evaluated"]["step"]["primary"][0], 130.0)
        self.assertAlmostEqual(n["evaluated"]["ramp"]["primary"][-1], 120.0)
        self.assertEqual(len(n["bounce_evaluated"]["speed_factor"]), len(T.SPIN_GRID))

    def test_yaml_and_csv_writers(self):
        with tempfile.TemporaryDirectory() as d:
            y = os.path.join(d, "t.yaml")
            T.write_yaml(self.dec, y, "test", "step")
            text = open(y).read()
            self.assertTrue(text.startswith("# Generated by: test"))
            self.assertIn("sha256", text)
            try:
                import yaml  # optional check of the hand-written emitter
            except ImportError:
                yaml = None
            if yaml:
                doc = yaml.safe_load(text)
                self.assertEqual(doc["rows"][0]["name"], "FlatNormal")
            c = os.path.join(d, "t.csv")
            n = T.write_trajectories(self.dec, c, "test", ("step", "ramp"))
            self.assertEqual(n, 4)  # one scenario x two modes x f4c {1, 0}
            with open(c) as fh:
                rows = list(csv.DictReader(l for l in fh if not l.startswith("#")))
            self.assertEqual(len(rows), 4)
            self.assertTrue(all(float(r["init_kmh"]) > 0 for r in rows))


class BallModelTests(unittest.TestCase):
    def test_closed_form_hits_target(self):
        B = ball_model.Ball(0.05)
        B.P0, B.P1, B.tau = [-12.0, 0.9, 1.0], [11.0, 0.0, -2.0], 1.0
        p = B.pos1(1.0)
        self.assertAlmostEqual(p[0], 11.0, 6)
        self.assertAlmostEqual(p[1], 0.0, 6)
        self.assertAlmostEqual(p[2], -2.0, 6)
        # derivative of |v0|^2 matches a finite difference
        h = 1e-5
        fd = (B.v2_initial(1.0 + h) - B.v2_initial(1.0 - h)) / (2 * h)
        self.assertAlmostEqual(B.dv2_initial(1.0), fd, 3)

    def test_initial_speed_template(self):
        data, _ = build()
        row = T.decode_all(data)["files"][0]["rows"][0]
        zero = {"type": "const", "value": 0.0}
        row["spin"] = {k: {"lo": zero, "hi": zero} for k in "abc"}   # the builder's spins (1.5) are not realistic
        m = ball_model.simulate(row, T, (-1250, 100, 150), (1100, 0, -250), blend=0.5, sec_weight=1.0)
        self.assertAlmostEqual(m["init_kmh"], 130.0, delta=2.5)
        self.assertEqual(m["bounce_tick"], round(m["tau"] * 60))
        self.assertGreater(m["net_clear_m"], 0.0)
        self.assertTrue(math.isfinite(m["out_kmh"]))


