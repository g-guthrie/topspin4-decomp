#!/usr/bin/env python3
"""Convert a XenonRecomp config made by tools/recomp_config.py into a ReXGlue
codegen include file ([functions] + [[switch_tables]]).

    python3 tools/recomp/to_rexglue.py MODULE.toml OUT.toml [--setjmp A --longjmp A]
        [--functions all|none] [--no-switches]

Only the subset of TOML that recomp_config.py writes is parsed (standard
library only). ReXGlue has no "impossible case" marker, so cases whose table
entry lands on padding (label 0) are mapped to the first real label and
counted in the summary line.
"""
import argparse
import re
import sys

FUNC_RE = re.compile(r"\{\s*address\s*=\s*(0x[0-9A-Fa-f]+)\s*,\s*size\s*=\s*(0x[0-9A-Fa-f]+)\s*\}")
NUM = r"(0x[0-9A-Fa-f]+|\d+)"


def parse_functions(text):
    return [(int(a, 16), int(s, 16)) for a, s in FUNC_RE.findall(text)]


def parse_switches(text):
    out = []
    for block in text.split("[[switch]]")[1:]:
        base = re.search(r"base\s*=\s*" + NUM, block)
        reg = re.search(r"\br\s*=\s*" + NUM, block)
        labels = re.search(r"labels\s*=\s*\[([^\]]*)\]", block)
        if not (base and reg and labels):
            raise ValueError("malformed [[switch]] block: %r" % block[:80])
        lab = [int(x, 0) for x in labels.group(1).replace(",", " ").split()]
        out.append((int(base.group(1), 0), int(reg.group(1), 0), lab))
    return out


def render(functions, switches, setjmp=None, longjmp=None):
    lines = ["# Generated by tools/recomp/to_rexglue.py"]
    if setjmp:
        lines.append("setjmp_address = 0x%08X" % setjmp)
    if longjmp:
        lines.append("longjmp_address = 0x%08X" % longjmp)
    impossible = 0
    if functions:
        lines.append("")
        lines.append("[functions]")
        for a, s in functions:
            lines.append('"0x%08X" = { size = 0x%X }' % (a, s))
    for base, reg, labels in switches:
        real = [l for l in labels if l]
        if not real:
            continue
        fixed = []
        for l in labels:
            if l == 0:
                impossible += 1
                fixed.append(real[0])
            else:
                fixed.append(l)
        lines.append("")
        lines.append("[[switch_tables]]")
        lines.append("address = 0x%08X" % base)
        lines.append("register = %d" % reg)
        lines.append("labels = [%s]" % ", ".join("0x%08X" % l for l in fixed))
    return "\n".join(lines) + "\n", impossible


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("module_toml")
    ap.add_argument("out")
    ap.add_argument("--switches", help="switch table TOML (default: from switch_table_file_path)")
    ap.add_argument("--functions", choices=["all", "none"], default="all")
    ap.add_argument("--only", help="comma-separated hex addresses: emit just these functions")
    ap.add_argument("--no-switches", action="store_true")
    ap.add_argument("--setjmp", type=lambda x: int(x, 0))
    ap.add_argument("--longjmp", type=lambda x: int(x, 0))
    a = ap.parse_args(argv)

    text = open(a.module_toml).read()
    funcs = parse_functions(text) if a.functions == "all" else []
    if a.only:
        want = {int(x, 16) for x in a.only.split(",")}
        funcs = [f for f in parse_functions(text) if f[0] in want]
    sw = []
    if not a.no_switches:
        path = a.switches
        if not path:
            m = re.search(r'switch_table_file_path\s*=\s*"([^"]+)"', text)
            if m:
                import os
                path = os.path.join(os.path.dirname(a.module_toml), m.group(1))
        if path:
            sw = parse_switches(open(path).read())
    out, impossible = render(funcs, sw, a.setjmp, a.longjmp)
    with open(a.out, "w") as f:
        f.write(out)
    print("to_rexglue: %d functions, %d switch tables, %d impossible cases remapped"
          % (len(funcs), len(sw), impossible))
    return 0


if __name__ == "__main__":
    sys.exit(main())
