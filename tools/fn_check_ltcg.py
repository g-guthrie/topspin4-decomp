@dataclass
class MapSymbol:
    name: str
    address: int
    obj: str
    is_function: bool


def parse_map(text: str) -> list[MapSymbol]:
    """Publics and statics of a link.exe /MAP file."""
    out = []
    _head, _, body = text.partition("Publics by Value")
    for line in body.splitlines():
        parts = line.split()
        if len(parts) < 4 or ":" not in parts[0] or parts[0].startswith("0000:"):
            continue
        try:
            address = int(parts[2], 16)
        except ValueError:
            continue
        is_function = len(parts) >= 5 and parts[3] == "f"
        out.append(MapSymbol(parts[1], address, parts[-1], is_function))
    return out


class SymbolIndex:
    """Address -> name lookup with offsets; prefers real names over stubs."""

    def __init__(self, entries: list[tuple[str, int]], stub_names: dict[str, str] | None = None):
        stub_names = stub_names or {}
        by_addr: dict[int, str] = {}
        for name, address in entries:
            name = stub_names.get(name, name)
            old = by_addr.get(address)
            if old is None or (old.startswith("lt1stub_") and not name.startswith("lt1stub_")):
                by_addr[address] = name
        self.addrs = sorted(by_addr)
        self.names = [by_addr[a] for a in self.addrs]
        self.by_name = {}
        for a, n in zip(self.addrs, self.names):
            self.by_name.setdefault(n, a)

    def lookup(self, address: int) -> tuple[str, int] | None:
        import bisect
        i = bisect.bisect_right(self.addrs, address) - 1
        if i < 0:
            return None
        return self.names[i], address - self.addrs[i]


# --------------------------------------------------------------------------- relocation rebuild

def _sext16(v: int) -> int:
    return v - 0x10000 if v & 0x8000 else v


def branch_target(word: int, address: int) -> int | None:
    op = word >> 26
    if op == 18:
        disp = word & 0x03FFFFFC
        if disp & 0x02000000:
            disp -= 0x04000000
        return (disp if word & 2 else address + disp) & 0xFFFFFFFF
    if op == 16:
        disp = word & 0xFFFC
        if disp & 0x8000:
            disp -= 0x10000
        return (disp if word & 2 else address + disp) & 0xFFFFFFFF
    return None


@dataclass
class Site:
    offset: int      # byte offset of the instruction/word in the function
    kind: int        # REL24 / REL14 / ADDR32 / REFHI / REFLO
    address: int     # resolved absolute target address


def candidate_sites(image: Image, start: int, code: bytes) -> list[Site]:
    """Rebuild relocation sites of a linked function from its bytes and base relocs."""
    end = start + len(code)
    sites = []
    highs: list[tuple[int, int, int]] = []  # (offset, dest reg, full address)
    words = [int.from_bytes(code[i : i + 4], "big") for i in range(0, len(code), 4)]
    for index, word in enumerate(words):
        address = start + index * 4
        reloc = image.base_relocs.get(address) or image.base_relocs.get(address + 2)
        if reloc:
            kind, param = reloc
            if kind == 3:  # HIGHLOW: an absolute word (jump table entry)
                sites.append(Site(index * 4, ADDR32, word))
            elif kind == 4:  # HIGHADJ on lis/addis
                full = ((word & 0xFFFF) << 16) + _sext16(param)
                highs.append((index * 4, (word >> 21) & 31, full & 0xFFFFFFFF))
                sites.append(Site(index * 4, REFHI, full & 0xFFFFFFFF))
            elif kind == 2:  # LOW on addi/lwz/stw/...
                low, base_reg = word & 0xFFFF, (word >> 16) & 31
                full = None
                for _off, reg, value in reversed(highs):
                    if reg == base_reg and (value & 0xFFFF) == low:
                        full = value
                        break
                if full is None:
                    for _off, _reg, value in reversed(highs):
                        if (value & 0xFFFF) == low:
                            full = value
                            break
                sites.append(Site(index * 4, REFLO, full if full is not None else -1))
            continue
        target = branch_target(word, address)
        # A branch to the function's own first instruction is a recursive call
        # (the target object has a REL24 to itself there), never a local loop.
        if target is not None and (target == start or not (start <= target < end)):
            sites.append(Site(index * 4, REL24 if word >> 26 == 18 else REL14, target))
    return sites


def target_sites(code: bytes, start: int, relocs: list[Reloc]) -> list[Site]:
    """Relocation sites of the target, with addresses decoded from the linked original."""
    words = [int.from_bytes(code[i : i + 4], "big") for i in range(0, len(code), 4)]
    sites = []
    highs: list[tuple[int, str, int, int]] = []  # index, symbol, high half, lis destination register
    for r in sorted(relocs, key=lambda r: r.offset):
        index = r.offset // 4
        if index >= len(words):
            continue
        word = words[index]
        if r.kind in (REL24, REL14):
            sites.append(Site(index * 4, r.kind, branch_target(word, start + index * 4)))
        elif r.kind == ADDR32:
            sites.append(Site(index * 4, ADDR32, word))
        elif r.kind == REFHI:
            highs.append((index, r.symbol, (word & 0xFFFF) << 16, (word >> 21) & 31))
            sites.append(Site(index * 4, REFHI, -1))
        elif r.kind in (REFLO, 0x4):
            low = _sext16(word & 0xFFFF)
            # The high half is the latest lis of this symbol into the register the low half is
            # based on: two lis/lo pairs of one symbol can interleave. Else the latest lis.
            base = (word >> 16) & 31
            hi = (next((h for h in reversed(highs) if h[1] == r.symbol and h[3] == base), None)
                  or next((h for h in reversed(highs) if h[1] == r.symbol), None))
            full = ((hi[2] + low) & 0xFFFFFFFF) if hi else -1
            sites.append(Site(index * 4, REFLO, full))
            if hi:
                for s in sites:
                    if s.offset == hi[0] * 4 and s.kind == REFHI and s.address == -1:
                        s.address = full
    return sites


def masked(code: bytes, sites: list[Site]) -> list[int]:
    words = [int.from_bytes(code[i : i + 4], "big") for i in range(0, len(code), 4)]
    for s in sites:
        i = s.offset // 4
        if i < len(words):
            words[i] &= ~MASKS[s.kind] & 0xFFFFFFFF
    return words


# --------------------------------------------------------------------------- comparison

@dataclass
class Result:
    ok: bool
    problems: list[str]
    renames: dict[str, str]
    pools: list[str]
    diff_words: list[int]
    stale: dict[str, str] = field(default_factory=dict)  # old placeholder -> current name


def compare(c_code: bytes, c_sites: list[Site], c_start: int, c_index: SymbolIndex,
            c_read, t_code: bytes, t_sites: list[Site], t_start: int, t_index: SymbolIndex,
            t_read, known_names: set[str], aliases=None, name_address: dict | None = None) -> Result:
    problems: list[str] = []
    renames: dict[str, str] = {}
    pools: list[str] = []
    stale: dict[str, str] = {}
    name_address = name_address or {}
    size = len(t_code)
    if len(c_code) < size or any(c_code[size:].strip(b"\0")):
        problems.append(f"size {len(c_code):#x} != target {size:#x}")
    c_code = c_code[:size]
    c_sites = [s for s in c_sites if s.offset < size]
    tw, cw = masked(t_code, t_sites), masked(c_code, c_sites)
    diff = [i for i in range(max(len(tw), len(cw)))
            if (tw[i] if i < len(tw) else None) != (cw[i] if i < len(cw) else None)]
    if diff:
        problems.append(f"{len(diff)} differing instruction(s), first at +{diff[0] * 4:#x}")
    t_layout = sorted((s.offset, s.kind) for s in t_sites)
    c_layout = sorted((s.offset, s.kind) for s in c_sites)
    if t_layout != c_layout:
        problems.append(f"relocation layout differs (target {len(t_layout)}, candidate {len(c_layout)})")
    if not problems:
        t_by = {(s.offset, s.kind): s for s in t_sites}
        for cs in c_sites:
            ts = t_by[(cs.offset, cs.kind)]
            where = f"+{cs.offset:#x}"
            c_in = c_start < cs.address < c_start + size
            t_in = t_start < ts.address < t_start + size
            if c_in or t_in:
                if not (c_in and t_in and cs.address - c_start == ts.address - t_start):
                    problems.append(f"{where}: local label differs")
                continue
            c_sym = c_index.lookup(cs.address) if cs.address >= 0 else None
            t_sym = t_index.lookup(ts.address) if ts.address >= 0 else None
            if c_sym is None and t_sym is not None and cs.address >= 0:
                # LTCG emits literals and trimmed static const data without a
                # map symbol: compare the value, as for a named pool.
                c_sym = ("__pool@anonymous", 0)
            if c_sym is None or t_sym is None:
                problems.append(f"{where}: unresolved target ({cs.address:#x} / {ts.address:#x})")
                continue
            (cn, co), (tn, to) = c_sym, t_sym
            if cn.startswith(POOL_PREFIXES):
                width = 8 if cs.kind in (REFHI, REFLO) else 4
                cv, tv = c_read(cs.address, width), t_read(ts.address, width)
                if cv[:4] == tv[:4]:
                    pools.append(f"{where}: {cn}+{co:#x} = {tn}+{to:#x} ({cv[:4].hex()})")
                    continue
                problems.append(f"{where}: pooled constant {cv[:4].hex()} != target {tv[:4].hex()} ({tn}+{to:#x})")
                continue
            if aliases is not None and cn in aliases:
                # A reviewed alias (icf_aliases.json) equals the symbol at its own address only.
                if not (co == to and aliases.same(cn, ts.address - to)):
                    problems.append(f"{where}: alias {cn}+{co:#x} stands for {aliases.address(cn):#010x}, "
                                    f"target {tn}+{to:#x}")
                continue
            if cn != tn and co == to and name_address.get(cn) == ts.address - to:
                continue  # two symbols.txt names at one address (0x8814B440 up to b224)
            if cn != tn and co == to and cn not in known_names and not tn.startswith(PLACEHOLDER_PREFIXES) \
                    and icf_alias.placeholder_address(cn) == ts.address - to:
                stale[cn] = tn  # the placeholder of an older split: it encodes this address
                continue
            if co != to:
                problems.append(f"{where}: {cn}+{co:#x} vs target {tn}+{to:#x}")
            elif cn == tn:
                continue
            elif tn.startswith(PLACEHOLDER_PREFIXES) and cn not in known_names:
                prev = renames.get(tn)
                if prev and prev != cn:
                    problems.append(f"{tn} named both {prev} and {cn}")
                renames[tn] = cn
            else:
                problems.append(f"{where}: candidate {cn} vs target {tn}")
    return Result(not problems, problems, renames, pools, diff, stale)


