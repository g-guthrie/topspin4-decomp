def build(primary: Path, contexts: list[str], flags: list[str], includes: list[str],
          toolchain: Path, wibo: Path, workdir: Path, code_names: set[str] | None = None,
          verbose: bool = True) -> tuple[Image, list[MapSymbol], dict[str, str]]:
    cl, link = toolchain / "cl.exe", toolchain / "link.exe"
    objects = []
    sources = [("gl", [], primary)] + [parse_context(c) for c in contexts]
    incdirs = {ROOT / "src" / "xbox360"} | {s.resolve().parent for _k, _f, s in sources}
    inc = ["/I" + os.path.relpath(d, workdir) for d in sorted(incdirs)]
    for index, (mode, own_flags, source) in enumerate(sources):
        local = workdir / f"u{index}_{source.name}"
        shutil.copyfile(source, local)
        gl = ["/GL"] if mode == "gl" else []
        result = run([str(wibo), str(cl), *BASE_FLAGS, *gl, *flags, *own_flags, *inc, local.name],
                     workdir)
        obj = local.with_suffix(".obj")
        if result.returncode or not obj.is_file():
            sys.stdout.write(result.stdout + result.stderr)
            raise BuildError(f"compile failed: {source}", source, result.stdout + result.stderr, workdir)
        objects.append(obj.name)
    base_cmd = [str(wibo), str(link), *LINK_FLAGS, *[f"/INCLUDE:{n}" for n in includes]]
    # Pass 1: discover externals.
    first = run(base_cmd + ["/FORCE:UNRESOLVED", "/out:probe.dll", *objects], workdir)
    if "caught SIG" in first.stdout + first.stderr:  # no externals after a crash: stop here
        # Its unresolved-symbol lines name every object, so none of them is passed on as a culprit.
        raise BuildError("linker crashed", None, "", workdir)
    unresolved = sorted({m.group(1) or m.group(2) for m in UNRESOLVED.finditer(first.stdout + first.stderr)
                         if not (m.group(1) or m.group(2)).startswith("__imp_")})
    if code_names is None:
        code_names = {e[0] for e in load_symbols() if e[1] == ".text"}
    stub_c, alias = stub_source(unresolved, code_names)
    (workdir / "lt1stubs.c").write_text(stub_c)
    result = run([str(wibo), str(cl), *BASE_FLAGS, "lt1stubs.c"], workdir)
    if result.returncode:
        sys.stdout.write(result.stdout + result.stderr)
        raise SystemExit("stub compile failed")
    alt = [f"/ALTERNATENAME:{alias[s]}={s}" for s in alias]
    rsp = workdir / "link.rsp"
    rsp.write_text("\n".join(alt + objects + ["lt1stubs.obj"]) + "\n")
    second = run(base_cmd + ["/MAP:out.map", "/out:out.dll", "@link.rsp"], workdir)
    if not (workdir / "out.dll").is_file() or not (workdir / "out.map").is_file():
        sys.stdout.write(second.stdout + second.stderr)
        if "caught SIG" in second.stdout + second.stderr:
            raise BuildError("linker crashed", None, "", workdir)
        raise BuildError("link failed", None, second.stdout + second.stderr, workdir)
    for line in (second.stdout + second.stderr).splitlines():
        if verbose and ("error" in line or "warning" in line):
            print("  " + line.strip())
    image = parse_pe((workdir / "out.dll").read_bytes())
    symbols = parse_map((workdir / "out.map").read_text(errors="replace"))
    return image, symbols, alias


def function_extent(image: Image, symbols: list[MapSymbol], address: int) -> int:
    """Length of a linked function from .pdata, else up to the next map symbol."""
    for name, va, vsize, raw in image.sections:
        if name != ".pdata" or not raw:
            continue
        table = image.data[raw : raw + vsize]
        for pos in range(0, len(table) - 7, 8):
            begin, info = struct.unpack_from(">II", table, pos)
            if begin == address:
                return ((info >> 8) & 0x3FFFFF) * 4
    later = sorted(s.address for s in symbols if s.address > address
                   and image.section_of(s.address) == image.section_of(address))
    text_end = next(image.base + va + vs for n, va, vs, _r in image.sections
                    if va <= address - image.base < va + vs)
    return (later[0] if later else text_end) - address


@dataclass
class Checked:
    candidate: str
    target: str
    t_start: int
    result: Result | None      # None: the candidate is not in the linked image
    c_code: bytes = b""
    t_code: bytes = b""
    c_sites: list = field(default_factory=list)
    t_sites: list = field(default_factory=list)


class LazyImage:
    """The original module image, read only when a pooled constant needs its value."""

    def __init__(self, path: Path):
        self.path, self.image = path, None

    def read(self, address: int, size: int) -> bytes:
        if self.image is None:
            if not self.path.is_file():
                raise SystemExit(f"{self.path} is needed to compare a pooled constant")
            self.image = parse_pe(self.path.read_bytes(), base_relocs=False)
        return self.image.read(address, size)


def verify(source: Path, contexts: list[str], flags: list[str], pairs: list[tuple[str, str]],
           find_target, symbols: list, no_include: bool = False, toolchain: Path = TOOLCHAIN,
           wibo: Path = WIBO, target_image: Path = TARGET_IMAGE, keep: bool = False,
           verbose: bool = True, extra_includes: list[str] | None = None) -> tuple[list[Checked], SymbolIndex, SymbolIndex, Path]:
    """Compile+link once and compare every (candidate, target name) pair.

    find_target(name) -> (start address, code bytes, relocations) reads the split
    target object; its code bytes are the linked original (Jeff keeps them).
    """
    if not (toolchain / "OLEAUT32.dll").is_file():
        raise SystemExit(f"{toolchain} is not prepared: run tools/fn_check_ltcg.py --setup")
    known_names = {e[0] for e in symbols}
    code_names = {e[0] for e in symbols if e[1] == ".text"}
    t_index = SymbolIndex([(e[0], e[2]) for e in symbols])
    t_read = LazyImage(target_image).read
    aliases = icf_alias.AliasMap()
    name_address = {}
    for entry in symbols:
        name_address.setdefault(entry[0], entry[2])
    text_addresses = {e[2] for e in symbols if e[1] == ".text"}
    code_names |= {e.alias for e in aliases.entries if e.address in text_addresses}  # function stubs
    workdir = Path(tempfile.mkdtemp(prefix="ltcgcheck-", dir=scratch_parent()))
    includes = ([] if no_include else [c for c, _ in pairs]) + list(extra_includes or [])
    image, map_symbols, alias = build(source, contexts, flags, includes, toolchain, wibo,
                                      workdir, code_names, verbose)
    c_index = SymbolIndex([(s.name, s.address) for s in map_symbols], alias)
    out = []
    for cand, tname in pairs:
        t_start, t_code, t_relocs = find_target(tname)
        entry = next((s for s in map_symbols if s.name == cand), None)
        if entry is None:
            out.append(Checked(cand, tname, t_start, None, t_code=t_code))
            continue
        length = function_extent(image, map_symbols, entry.address)
        c_code = image.read(entry.address, length)
        c_sites = candidate_sites(image, entry.address, c_code)
        t_sites = target_sites(t_code, t_start, t_relocs)
        res = compare(c_code, c_sites, entry.address, c_index, image.read,
                      t_code, t_sites, t_start, t_index, t_read, known_names, aliases, name_address)
        out.append(Checked(cand, tname, t_start, res, c_code, t_code, c_sites, t_sites))
    if not keep and all(c.result and c.result.ok for c in out):
        shutil.rmtree(workdir, ignore_errors=True)
    return out, c_index, t_index, workdir


def auto_contexts(args, pairs, symbols, find_function) -> list[str]:
    """--auto-context: explicit contexts, then the matched sources of the callees, primer last."""
    names = {e[2]: e[0] for e in symbols if e[1] == ".text"}
    by_name = {e[0]: e[2] for e in symbols if e[1] == ".text"}

    def callees_of(address):
        try:
            _path, start, code, relocs = find_function(names[address])
        except (KeyError, SystemExit):
            return []
        return [a for a in auto.callee_addresses(code, start, relocs)
                if a in names and not auto.HELPER.match(names[a])]

    source_map = auto.load_source_map(ROOT, address_of=by_name.get)
    targets = [by_name[t] for _c, t in pairs]
    callees = auto.call_graph(targets, callees_of, lambda a: a in source_map, args.auto_depth)
    address_of = {c.symbol: a for a, cands in source_map.items() for c in cands}
    address_of.update(by_name)
    text = args.source.read_text(errors="replace")
    direct = {a for t in targets for a in callees_of(t)}
    inlined = [a for a in auto.referenced_addresses(text, address_of.get, skip=set(targets) | direct)
               if a in names and not auto.HELPER.match(names[a])]
    # What SRC declares each callee to return, under any name a candidate source gives it.
    wants = {}
    for address in [*callees, *inlined]:
        for name in dict.fromkeys([names.get(address, "")] + [c.symbol for c in source_map.get(address, [])]):
            kind = auto.return_kind(text, name) if name else None
            if kind:
                wants[address] = kind
                break
    texts = {}

    def returns_of(cand):
        if cand.source not in texts:
            texts[cand.source] = (ROOT / cand.source).read_text(errors="replace")
        return auto.return_kind(texts[cand.source], cand.symbol, definition=True)

    sel = auto.choose(callees, source_map, args.source, ROOT, targets, args.auto_prefix or "",
                      manual=args.context, inlined=inlined, recorded=auto.load_recorded(ROOT),
                      flags=args.flags, wants=wants, returns_of=returns_of)
    # Helpers that only a context-only file defines (folding stand-ins the link inlines): the
    # source names them, so their file is in every link, like an explicit --context.
    have = {auto.split_context(c)[1] for c in sel.contexts}
    for entry in auto.helper_contexts(text, auto.load_helpers(ROOT, address_of.get)):
        if auto.split_context(entry)[1] not in have and auto.split_context(entry)[1] != str(args.source):
            at = len(sel.contexts) - (1 if sel.contexts and sel.contexts[-1] == auto.PRIMER else 0)
            sel.contexts.insert(at, entry)
            HELPER_CONTEXTS.append(entry)
            sel.notes.append(f"{entry}: defines a helper the source names (context-only file)")
    for address, cand in sel.covered.items():
        if address in direct and cand.symbol not in text:
            sel.notes.append(f"{args.source.name} does not mention {cand.symbol}: a call under "
                             f"another name does not use the context body")
    print("\n".join(auto.report(sel, lambda a: names.get(a, "?"), args.auto_depth)))
    if not args.auto_no_include:
        args.include += [n for n in sel.includes() if n not in args.include]
    called = {names[t]: [sel.covered[a] for a in callees_of(t) if a in sel.covered] for t in targets}
    for cand_list in called.values():   # where each callee is, for counting its call sites
        for cand in cand_list:
            CALLEE_ADDRESS[cand] = next(a for a, c in sel.covered.items() if c == cand)
    return sel.contexts, called, {c.symbol: c.source for c in sel.covered.values()}


def matched(checked: list[Checked]) -> bool:
    return all(c.result and c.result.ok for c in checked)


HELPER_CONTEXTS: list = []  # context-only helper files the source names: kept in every fallback
CALLEE_ADDRESS: dict = {}   # Candidate -> address of the callee in the original (auto_contexts)


def inlined_sources(checked: list[Checked], c_index: SymbolIndex, called: dict, text: str,
                    addresses: dict | None = None) -> list:
    """Chosen callees (Candidate) the original calls more often than the linked candidate does:
    the link inlined them, at every call site or at some (or SRC does not call them: only
    callees SRC names are reported). addresses: Candidate -> callee address in the original;
    without it only a callee with no call left in the candidate is reported."""
    addresses = CALLEE_ADDRESS if addresses is None else addresses
    out = []
    for item in checked:
        if item.result is None:
            continue
        hits = [c_index.lookup(s.address) for s in item.c_sites if s.kind == REL24 and s.address >= 0]
        present = [hit[0] for hit in hits if hit and hit[1] == 0]
        for c in called.get(item.target, []):
            if c.symbol not in text or c in out:
                continue
            have = present.count(c.symbol)
            want = sum(1 for s in item.t_sites if s.kind == REL24 and s.address == addresses[c]) \
                if c in addresses else 1
            if have < want or have == 0:
                out.append(c)
    return out


def failing_context(error: BuildError, contexts: list[str], manual: int, guess: bool = True) -> str | None:
    """The automatic context to drop after a failed build, or None when none is to blame.

    Sources are compiled as u<index>_<name>, index 0 being the source under test and
    contexts[i] index i + 1; the first `manual` contexts are explicit and never dropped.
    A compile failure names its source. A link failure names objects (LNK2005 "X already
    defined in Y", LNK2001 for an import the stubs cannot stand in for): the last automatic
    one named goes. With no object named and `guess`,
    the last automatic context goes, so repeated failures end at the explicit contexts alone.
    """
    droppable = list(range(manual, len(contexts)))
    if contexts and droppable and parse_context(contexts[-1])[2].as_posix() == auto.PRIMER:
        droppable.pop()  # the pool primer stays
    if error.source is not None:
        hit = [i for i in droppable if parse_context(contexts[i])[2] == error.source]
        return contexts[hit[0]] if hit else None
    errors = "\n".join(line for line in error.output.splitlines() if "error" in line)
    named = [int(n) - 1 for n in re.findall(r"\bu(\d+)_\S+?\.obj", errors)]
    hit = [i for i in named if i in droppable]
    if hit:
        return contexts[max(hit)]
    return contexts[droppable[-1]] if droppable and guess else None


def explicit_command(args, contexts: list[str]) -> str:
    import shlex
    parts = ["python3", "tools/fn_check_ltcg.py", str(args.source), *args.mappings]
    if args.flags:
        parts += ["--flags", *args.flags]
    for name in args.include:
        parts += ["--include", name]
    if args.no_include:
        parts.append("--no-include")
    for context in contexts:
        parts += ["--context", context]
    return " ".join(shlex.quote(p) for p in parts)


def scratch_parent() -> Path:
    """Where the ltcgcheck-* scratch directories go: work/, or TS4_LTCG_SCRATCH (one per worker of a
    parallel run, so a worker that is killed leaves its scratch where the runner can remove it)."""
    value = os.environ.get("TS4_LTCG_SCRATCH")
    parent = Path(value).expanduser().absolute() if value else ROOT / "work"
    parent.mkdir(parents=True, exist_ok=True)
    return parent


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("source", type=Path, nargs="?")
    parser.add_argument("mappings", nargs="*", help="candidate_name=target_name_or_0xaddr")
    parser.add_argument("--context", action="append", default=[],
                        help="extra source in the same link; prefixes: nogl: (compile without /GL), "
                             "flags(/Ob1 ...): (extra cl flags for this source only)")
    parser.add_argument("--flags", nargs="*", default=[], help="extra cl flags for every /GL source")
    parser.add_argument("--no-include", action="store_true",
                        help="do not force the mapped functions with /INCLUDE")
    parser.add_argument("--include", action="append", default=[],
                        help="also force this symbol with /INCLUDE (keeps a context callee's standard "
                             "calling convention when it has other callers in the original)")
    parser.add_argument("--auto-context", action="store_true",
                        help="add the matched sources of the mapped functions' callees as contexts, "
                             "pool primer last; prints the contexts and the missing callee bodies")
    parser.add_argument("--auto-depth", type=int, default=1, choices=(1, 2),
                        help="1: direct callees (default); 2: also the callees of matched callees")
    parser.add_argument("--auto-prefix", default=None,
                        help='fixed prefix for every chosen source, e.g. "flags(/Ob1):" or "" (default: '
                             'plain, then flags(/Ob1): for a source whose callee the link inlined)')
    parser.add_argument("--auto-no-include", action="store_true",
                        help="do not force the called context callees with /INCLUDE")
    parser.add_argument("--auto-no-fallback", action="store_true",
                        help="on FAIL, do not also try without the /INCLUDEs and without the callee sources")
    parser.add_argument("--auto-tries", type=int, default=12,
                        help="on FAIL, how many smaller links to try at most (default 12)")
    parser.add_argument("--keep", action="store_true", help="keep the scratch directory")
    parser.add_argument("--quiet", action="store_true", help="omit listings for failures")
    parser.add_argument("--setup", action="store_true", help="prepare work/ltcg-toolchain and exit")
    parser.add_argument("--toolchain", type=Path, default=TOOLCHAIN)
    parser.add_argument("--wibo", type=Path, default=WIBO)
    args = parser.parse_args()
    if args.setup:
        setup(args.toolchain)
        return 0
    if args.source is None or not args.mappings:
        parser.error("source and at least one mapping are required")

    from fn_asm import disassemble, find_function

    symbols = load_symbols()
    by_addr = {e[2]: e[0] for e in symbols if e[1] == ".text"}
    pairs = []
    for mapping in args.mappings:
        cand, _, target = mapping.partition("=")
        tname = by_addr.get(int(target, 16)) if target.lower().startswith("0x") else target
        if tname is None:
            raise SystemExit(f"no .text symbol at {target}")
        pairs.append((cand, tname))

    def find_target(name):
        _path, start, code, relocs = find_function(name)
        return start, code, relocs

    contexts, called, owner, no_inline = list(args.context), {}, {}, set()
    given_includes = list(args.include)
    if args.auto_context:
        contexts, called, owner = auto_contexts(args, pairs, symbols, find_function)
    while True:
        try:
            checked, c_index, t_index, workdir = verify(
                args.source, contexts, args.flags, pairs, find_target, symbols,
                no_include=args.no_include, toolchain=args.toolchain, wibo=args.wibo, keep=args.keep,
                extra_includes=args.include)
        except BuildError as error:
            # Only automatic contexts are dropped; a failure of the source under test or of an
            # explicit --context stays an error.
            manual = len(args.context)
            bad = failing_context(error, contexts, manual, guess=False) if args.auto_context else None
            drop_includes = bad is None and error.source is None and args.include != given_includes
            if not drop_includes and args.auto_context:
                bad = bad or failing_context(error, contexts, manual)
            if bad is None and not drop_includes:
                print(f"scratch: {error.workdir}")
                raise
            if error.workdir and not args.keep:
                shutil.rmtree(error.workdir, ignore_errors=True)
            if drop_includes:
                print(f"auto-context: {error} with the callees forced by /INCLUDE; repeating without "
                      f"them (only the explicit --include values stay).")
                args.include = given_includes
            else:
                print(f"auto-context: dropped {bad} ({error}); its callees are checked without their "
                      f"bodies. Repeating without it.")
                contexts = [c for c in contexts if c != bad]
                gone = parse_context(bad)[2].as_posix()
                args.include = [n for n in args.include if n in given_includes or owner.get(n) != gone]
            continue
        # Plain contexts first; a callee the link inlined gets /Ob1 on its source, once.
        again = [] if args.auto_prefix is not None or matched(checked) else [
            c for c in inlined_sources(checked, c_index, called, args.source.read_text(errors="replace"))
            if c.source not in no_inline]
        if not again:
            break
        for cand in again:
            if cand.source in no_inline:
                continue
            print(f"auto-context: {cand.symbol} is called in the original and not in the candidate "
                  f"(inlined): repeating with {auto.NO_INLINE}{cand.source}")
            no_inline.add(cand.source)
            contexts = auto.with_prefix(contexts, cand.source, auto.NO_INLINE)
        if not args.keep:
            shutil.rmtree(workdir, ignore_errors=True)
    if args.auto_context and not args.auto_no_fallback and not matched(checked):
        # In a small link the callee bodies, or forcing them, can also move a function away
        # from its match: try the ranked smaller links and say which one matches.
        variants = auto.fallback_variants(contexts, args.context + HELPER_CONTEXTS, args.include,
                                          given_includes, owner,
                                          limit=args.auto_tries)
        for label, ctx, inc in variants:
            try:
                other = verify(args.source, ctx, args.flags, pairs, find_target, symbols,
                               no_include=args.no_include, toolchain=args.toolchain, wibo=args.wibo,
                               verbose=False, extra_includes=inc)
            except BuildError as error:
                shutil.rmtree(error.workdir, ignore_errors=True)
                continue
            if matched(other[0]):
                print(f"auto-context: no match with the full context; MATCH {label}")
                if not args.keep:
                    shutil.rmtree(workdir, ignore_errors=True)
                (checked, c_index, t_index, workdir), contexts, args.include = other, ctx, inc
                break
            shutil.rmtree(other[3], ignore_errors=True)
        else:
            if variants:
                print(f"auto-context: no match with the full context or with {len(variants)} smaller link(s): "
                      + "; ".join(label for label, _c, _i in variants))
    if args.auto_context:
        print("explicit command: " + explicit_command(args, contexts))
    failures, renames = 0, {}
    for item in checked:
        cand, tname, t_start, res = item.candidate, item.target, item.t_start, item.result
        c_code, t_code, c_sites, t_sites = item.c_code, item.t_code, item.c_sites, item.t_sites
        if res is None:
            print(f"FAIL {cand}: not in the linked image (inlined or discarded?)")
            failures += 1
            continue
        if res.ok:
            renames.update(res.renames)
            print(f"MATCH {cand} vs {tname} @ {t_start:08X} size {len(t_code):#x} (ltcg)")
            for line in res.pools:
                print(f"  POOL {line}")
            for old, new in sorted(res.stale.items()):
                print(f"  STALE {old} is {new} now: write {new} (tools/fix_refs.py does it for a spec's source)")
            continue
        failures += 1
        print(f"FAIL {cand} vs {tname} @ {t_start:08X}: " + "; ".join(res.problems))
        if args.quiet:
            continue
        def as_relocs(sites, index):
            out = []
            for s in sites:
                hit = index.lookup(s.address) if s.address >= 0 else None
                label = f"{hit[0]}+{hit[1]:#x}" if hit and hit[1] else (hit[0] if hit else "?")
                out.append(Reloc(s.offset, label, s.kind))
            return out
        t_lines = disassemble(t_code, t_start, as_relocs(t_sites, t_index))
        c_lines = disassemble(c_code, t_start, as_relocs(c_sites, c_index))
        width = max((len(l) for l in t_lines), default=0)
        print(f"  {'TARGET'.ljust(width)}   CANDIDATE")
        for i in range(max(len(t_lines), len(c_lines))):
            left = t_lines[i] if i < len(t_lines) else ""
            right = c_lines[i][10:] if i < len(c_lines) else ""
            print(f"{'*' if i in res.diff_words else ' '} {left.ljust(width)} | {right}")
    for old, new in sorted(renames.items()):
        print(f"RENAME {old} -> {new}")
    if args.keep or failures:
        print(f"scratch: {workdir}")
    return 1 if failures else 0


if __name__ == "__main__":
    raise SystemExit(main())
