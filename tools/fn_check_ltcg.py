@dataclass
class Image:
    data: bytes
    base: int
    sections: list[tuple[str, int, int, int]]  # name, rva, virtual size, raw pointer
    base_relocs: dict[int, tuple[int, int]] = field(default_factory=dict)  # va -> (type, param)

    def read(self, address: int, size: int) -> bytes:
        rva = address - self.base
        for _name, va, vsize, raw in self.sections:
            if va <= rva < va + vsize:
                start = raw + rva - va
                chunk = self.data[start : start + min(size, va + vsize - rva)] if raw else b""
                return chunk + bytes(size - len(chunk))
        raise KeyError(f"{address:#x} not in image")

    def section_of(self, address: int) -> str | None:
        rva = address - self.base
        for name, va, vsize, _raw in self.sections:
            if va <= rva < va + vsize:
                return name
        return None


def parse_pe(data: bytes, base_relocs: bool = True) -> Image:
    pe = struct.unpack_from("<I", data, 0x3C)[0]
    count = struct.unpack_from("<H", data, pe + 6)[0]
    optional = struct.unpack_from("<H", data, pe + 20)[0]
    base = struct.unpack_from("<I", data, pe + 24 + 28)[0]
    sections = []
    for index in range(count):
        offset = pe + 24 + optional + 40 * index
        name, vsize, va, _rsize, raw = struct.unpack_from("<8sIIII", data, offset)
        sections.append((name.rstrip(b"\0").decode("latin-1"), va, vsize, raw))
    image = Image(data, base, sections)
    for name, va, vsize, raw in sections:
        if name != ".reloc" or not base_relocs:
            continue
        block = data[raw : raw + vsize]
        pos = 0
        while pos + 8 <= len(block):
            page, size = struct.unpack_from("<II", block, pos)
            if size < 8 or pos + size > len(block):
                break
            entries = [struct.unpack_from("<H", block, p)[0] for p in range(pos + 8, pos + size, 2)]
            i = 0
            while i < len(entries):
                kind, off = entries[i] >> 12, entries[i] & 0xFFF
                param = 0
                if kind == 4 and i + 1 < len(entries):  # HIGHADJ carries the low half next
                    param = entries[i + 1]
                    i += 1
                if kind:
                    image.base_relocs[base + page + off] = (kind, param)
                i += 1
            pos += size
    return image


