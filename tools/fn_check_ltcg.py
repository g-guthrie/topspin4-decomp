#!/usr/bin/env python3
"""Compile sources with /GL, link them with /LTCG, and compare named functions.

Usage:
  python3 tools/fn_check_ltcg.py SRC [--context SRC2 ...] name=0xADDR [...]
         [--flags /GS-] [--no-include] [--keep] [--quiet]
  python3 tools/fn_check_ltcg.py SRC name=0xADDR [...] --auto-context [--flags /Oc]
  python3 tools/fn_check_ltcg.py --setup        # build work/ltcg-toolchain once

Why: the Rich header of Swing_DLL.xex lists 362 objects of kind
Utc1600_LTCG_CPP (compiled with /GL, code generated by link.exe /LTCG), so
part of the game's code was generated at link time with whole-program
information. tools/fn_check.py compiles one object with cl.exe and cannot
reproduce that. This tool:

1. compiles SRC and every --context source with `/O2 /Oi /GL [--flags]`
   (a context source supplies callees or callers that must be in the same
   link so the code generator sees them; prefix a context path with `nogl:`
   to compile it without /GL);
2. links everything with the Xbox `link.exe /LTCG` into a scratch DLL
   (/dll /noentry /nodefaultlib /XEX:NO /OPT:NOREF /OPT:NOICF /MAP).
   Unresolved externals (callees, globals, __savegprlr_NN, _fltused, ...)
   are found by a first /FORCE:UNRESOLVED pass and then bound with
   /ALTERNATENAME to distinct stub definitions compiled *without* /GL, so
   every external gets its own address and the code generator treats it as
   opaque, as it would treat a library function;
3. reads the named functions out of the linked image, rebuilds their
   relocations (branch targets outside the function, and the image's own
   base relocations for lis/addi pairs and jump-table words), and compares
   them with the target the same way tools/fn_check.py does: instruction
   words with relocation fields masked, relocation layout, then relocation
   targets by symbol. Targets in the target image are resolved by address
   from the original module, so an addend (pool+0x68) is compared too.

Relocation targets are accepted when:
  - the names agree (stubs are reported under the external's own name);
  - the target is a placeholder (fn_/lbl_/...) and the candidate name is
    new: printed as RENAME, exactly like fn_check;
  - both point inside their own function at the same offset (jump tables);
  - the candidate points into an LTCG constant pool (`__pool@...`) or a
    `__real@` literal and the bytes there equal the target's bytes
    (reported as POOL lines; LTCG merges literals into pools whose name and
    order depend on the whole program, so only the value can be checked).

Exit status 0 means every mapping matched (with at most RENAME/POOL notes).

Scratch directories (ltcgcheck-*) are made in work/, or in the directory
TS4_LTCG_SCRATCH names: give each worker of a parallel run its own.

By default each mapped function is forced into the link with /INCLUDE.
Pass --no-include when a context source contains the function's real
caller(s): /INCLUDE makes the symbol externally visible, which stops LTCG
from giving it a private calling convention.

--auto-context chooses the contexts from the call graph (tools/ltcg_autocontext.py):
the direct callees of each mapped function are read from the original code
(--auto-depth 2 adds the callees of those callees), each callee is mapped to
the source that byte-matches it (config/54540859/match.json, then work/specs),
and those sources become contexts, each once, with the contexts recorded for a
callee that is itself an LTCG unit, the sources of functions SRC names but the
original does not call (the link inlined them), and
src/xbox360/pp1_pool_primer.c last. The called callees are forced with
/INCLUDE (they were matched as functions of their own; --auto-no-include turns
that off). Explicit --context values are kept in front. Contexts are compiled
plain; when the link inlines a callee the original calls, the check is
repeated with `flags(/Ob1):` on that callee's source (--auto-prefix P puts P on
every chosen source instead and repeats nothing). The chosen contexts, the
callees without a matched source ("missing callee bodies": match those first)
and the equivalent explicit command are printed. A context that fails to
compile, or that makes the link fail (two sources defining one function), is
dropped with a message and the check is repeated without it. When the result
is FAIL, smaller links are also tried in a fixed order (without the /INCLUDEs;
`flags(/Ob1):` on every callee source; without one callee source at a time; one
callee source alone; without the callee sources: at most --auto-tries of them;
before them, once, the failed link without the pool primer, for a function
whose literals the original keeps in another pool) and a MATCH there is reported with its explicit command: in a small link a
callee source can also disturb the function (a global declared with another
type there, a body whose register use the original did not have);
--auto-no-fallback skips this. A candidate source that defines a callee with
another return kind (void / a value) than SRC declares is passed over when
another candidate agrees, also for a stand-in. A callee the original calls more
often than the linked candidate (inlined at some call site) gets
`flags(/Ob1):` like one that is inlined everywhere.
"""

