#!/usr/bin/env python3
"""Build and measure matching units for the second target, Loader_DLL.xex.

Mirrors tools/matching.py for the Swing module, but keeps its own state so the
two targets never share a split or a unit table:

  config/54540859/loader/symbols.seed.txt  reviewed bootstrap symbols
  config/54540859/loader/splits.txt        reviewed unit boundaries
  config/54540859/loader/units.json        matching units (source, flags, symbols)
  config/54540859/loader/match.json        durable summary written by --record
  work/loader/                              analysis, split, rebuilt objects, report

The work directory has the same layout as work/matching, so the Swing helper
tools also work on Loader:

  TS4_MATCHING_DIR=work/loader python3 tools/fn_asm.py fn_83XXXXXX
  TS4_MATCHING_DIR=work/loader python3 tools/fn_check.py src/loader/foo.c name=0x83...

Loader sources live in src/loader/. Units are added by editing units.json and
splits.txt (one block per source, as for Swing); --record refuses to write a
summary unless every listed symbol is a 100% objdiff match.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
VERSION = "54540859"
MODULE = "Loader_DLL.xex"
CONFIG = ROOT / "config" / VERSION / "loader"
UNITS = CONFIG / "units.json"
SUMMARY = CONFIG / "match.json"
BASE_FLAGS = ["/nologo", "/c", "/O2", "/Oi"]


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1 << 20), b""):
            digest.update(block)
    return digest.hexdigest()


def run(command: list[str]) -> None:
    print("+", " ".join(command))
    subprocess.run(command, cwd=ROOT, check=True)


def load_units() -> list[dict]:
    return json.loads(UNITS.read_text(encoding="utf-8"))["units"]


def jeff_config(path: Path, xex: Path, symbols: Path, splits: Path, quick: bool) -> None:
    options = (
        "quick_analysis: true\nsymbols_known: true\n"
        "detect_objects: false\ndetect_strings: false\n"
        if quick else ""
    )
    path.write_text(
        f"object: {json.dumps(str(xex))}\n"
        f"symbols: {json.dumps(str(symbols))}\n"
        f"splits: {json.dumps(str(splits))}\n"
        f"write_asm: false\n{options}",
        encoding="utf-8",
    )


def objdiff_project(split_config: dict, rebuilt: dict[str, Path]) -> dict:
    units = []
    for unit in split_config["units"]:
        name = unit["name"]
        target = Path(unit["object"])
        entry = {
            "name": f"Loader_DLL/{name}",
            "target_path": str(target if target.is_absolute() else ROOT / target),
            "metadata": {"auto_generated": unit["autogenerated"],
                         "progress_categories": ["loader"]},
        }
        if name in rebuilt:
            entry["base_path"] = str(rebuilt[name])
            entry["metadata"].update({"complete": True, "source_path": name})
        units.append(entry)
    return {"min_version": "2.0.0-beta.5", "build_target": False, "units": units,
            "progress_categories": [{"id": "loader", "name": "Loader code"}]}


def check_units(report: dict, units: list[dict]) -> list[str]:
    found = {f["name"]: f for u in report.get("units", []) for f in u.get("functions", [])}
    problems = []
    for unit in units:
        for name, size in unit["symbols"].items():
            function = found.get(name)
            if function is None:
                problems.append(f"{name}: missing from the report")
            elif function.get("size") != str(size):
                problems.append(f"{name}: size {function.get('size')} != {size}")
            elif function.get("fuzzy_match_percent") != 100.0:
                problems.append(f"{name}: {function.get('fuzzy_match_percent')}%")
    return problems


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--xex", type=Path, default=ROOT / "orig" / VERSION / MODULE)
    parser.add_argument("--jeff", type=Path, required=True)
    parser.add_argument("--compiler-dir", type=Path, required=True)
    parser.add_argument("--wrapper", type=Path, required=True)
    parser.add_argument("--objdiff", type=Path, required=True)
    parser.add_argument("--work-dir", type=Path, default=ROOT / "work" / "loader")
    parser.add_argument("--fresh-analysis", action="store_true")
    parser.add_argument("--record", action="store_true",
                        help="write config/54540859/loader/match.json from a clean run")
    args = parser.parse_args()

    target = json.loads((ROOT / "config" / "target.json").read_text())
    expected = target["modules"][MODULE]
    if sha256(args.xex) != expected:
        raise SystemExit(f"wrong {MODULE} SHA-256 (expected {expected})")

    work = args.work_dir.expanduser().absolute()
    analysis, split, rebuilt_dir, project_dir = (work / d for d in ("analysis", "split", "rebuilt", "objdiff-project"))
    for directory in (analysis, split, rebuilt_dir, project_dir):
        directory.mkdir(parents=True, exist_ok=True)
    symbols = analysis / "symbols.txt"
    splits = analysis / "splits.txt"
    seed = CONFIG / "symbols.seed.txt"
    if args.fresh_analysis or not symbols.is_file():
        shutil.copyfile(seed, symbols)
    shutil.copyfile(CONFIG / "splits.txt", splits)
    config = analysis / "config.yml"
    jeff_config(config, args.xex.resolve(), symbols, splits, symbols.stat().st_size > seed.stat().st_size)
    run([str(args.jeff), "xex", "split", str(config), str(split)])

    compiler = args.compiler_dir / "cl.exe"
    units = load_units()
    rebuilt = {}
    for unit in units:
        obj = rebuilt_dir / (Path(unit["source"]).stem + ".obj")
        rebuilt[unit["source"]] = obj
        run([str(args.wrapper), str(compiler), *BASE_FLAGS, *unit.get("flags", []),
             f"/Fo{Path(obj).relative_to(ROOT) if obj.is_relative_to(ROOT) else obj}",
             unit["source"]])

    split_config = json.loads((split / "config.json").read_text())
    (project_dir / "objdiff.json").write_text(json.dumps(objdiff_project(split_config, rebuilt), indent=2) + "\n")
    report_path = project_dir / "report.json"
    run([str(args.objdiff), "report", "generate", "-p", str(project_dir), "-o", str(report_path), "-f", "json-pretty"])
    report = json.loads(report_path.read_text())
    problems = check_units(report, units)
    measures = report["measures"]
    matched = sum(size for unit in units for size in unit["symbols"].values())
    functions = sum(len(unit["symbols"]) for unit in units)
    print(f"Loader: {functions} matched functions, {matched}/{measures.get('total_code')} code bytes, "
          f"{measures.get('total_functions')} functions, {measures.get('total_units')} units")
    if problems:
        raise SystemExit("not exact:\n  " + "\n  ".join(problems[:20]))
    if args.record:
        total = int(measures["total_code"])
        SUMMARY.write_text(json.dumps({
            "schema_version": 1,
            "module": MODULE,
            "module_sha256": expected,
            "compiler": "Xbox 360 MSVC 16.00.10224.00",
            "matched_functions": functions,
            "matched_code_bytes": matched,
            "module_total_code_bytes": total,
            "module_matched_code_percent": round(100.0 * matched / total, 8) if total else 0.0,
            "module_total_functions": measures["total_functions"],
            "module_total_units": measures["total_units"],
            "basis": "objdiff-cli 3.7.1 over all Jeff 0.3.5 split units for Loader_DLL.xex",
        }, indent=2) + "\n")
        print(f"Recorded {SUMMARY.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
