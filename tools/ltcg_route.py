#!/usr/bin/env python3
"""LTCG verification route for tools/matching.py (and the integration tools).

Most of Swing_DLL's game code was compiled with /GL and generated by
`link.exe /LTCG` (see docs/ltcg-route.md). Functions that depend on that
(cross-object register knowledge, pooled constants, link-time inlining) are
verified by compiling their source with /GL, linking it with /LTCG together
with its context sources, extracting the linked bytes and comparing them with
the target (tools/fn_check_ltcg.py does the same interactively).

Units live in config/54540859/ltcg_units.json, written by
tools/integrate_match.py from specs with "route": "ltcg":

  [{"source": "src/xbox360/lt1_x.c", "object": "lt1_x.obj",
    "context": ["src/xbox360/other.c", "nogl:src/xbox360/third.c"],
    "flags": [], "no_include": false,
    "symbols": {"ts4_name_88660000": 1048}}]

For each unit, build_units() verifies every symbol and then writes the
"rebuilt" object that objdiff compares: the unit's split target object with
each verified function's code replaced by the bytes our compiler and linker
produced (relocation fields keep the split object's bits, because a linked
image has no relocations; the checker has already proved the relocation
targets equal). A unit that fails verification stops the build, like a plain
unit that is not a 100% match.
"""

from __future__ import annotations

import json
import struct
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from xcoff import ROOT, load_symbols, read_coff  # noqa: E402

UNITS_PATH = ROOT / "config" / "54540859" / "ltcg_units.json"


def load_units(path: Path = UNITS_PATH) -> list[dict]:
    if not path.is_file():
        return []
    return json.loads(path.read_text())


def expected_symbols(units: list[dict] | None = None) -> dict[str, int]:
    units = load_units() if units is None else units
    return {name: size for unit in units for name, size in unit["symbols"].items()}


def split_object(split_dir: Path, source: str) -> Path:
    return split_dir / "obj" / (source.rsplit(".", 1)[0] + ".obj")


def section_layout(data: bytes) -> list[tuple[int, int]]:
    """(raw pointer, size) of each section of a COFF object, 1-based order."""
    _machine, count, _stamp, _symoff, _nsym, optional, _chars = struct.unpack_from("<HHIIIHH", data, 0)
    out = []
    for index in range(count):
        _name, _vs, _va, size, raw = struct.unpack_from("<8sIIII", data, 20 + optional + 40 * index)
        out.append((raw, size))
    return out


def patch_object(target_obj: bytes, functions: list[tuple[str, bytes, list[int]]]) -> bytes:
    """Replace function code in a split object.

    functions: (symbol, candidate code, masks per word) where mask bits set are
    relocation-field bits that keep the target's value.
    """
    coff = read_coff_bytes(target_obj)
    layout = section_layout(target_obj)
    out = bytearray(target_obj)
    for name, code, masks in functions:
        symbol = next(s for s in coff.symbols if s.name == name and s.section > 0)
        raw, size = layout[symbol.section - 1]
        start = raw + symbol.value
        if symbol.value + len(code) > size:
            raise SystemExit(f"{name}: candidate code runs past its section")
        for i in range(0, len(code), 4):
            old = int.from_bytes(out[start + i : start + i + 4], "big")
            new = int.from_bytes(code[i : i + 4], "big")
            keep = masks[i // 4]
            word = (new & ~keep & 0xFFFFFFFF) | (old & keep)
            if word != old:
                raise SystemExit(f"{name}: candidate differs from the target at +{i:#x}")
            out[start + i : start + i + 4] = word.to_bytes(4, "big")
    return bytes(out)


def read_coff_bytes(data: bytes):
    import tempfile

    with tempfile.NamedTemporaryFile(suffix=".obj") as handle:
        handle.write(data)
        handle.flush()
        return read_coff(Path(handle.name))


def build_units(rebuilt_dir: Path, split_dir: Path, symbols_txt: Path, wibo: Path,
                toolchain: Path, target_image: Path | None = None,
                units: list[dict] | None = None) -> dict[str, Path]:
    """Verify every LTCG unit and write its rebuilt object; returns {source: object}."""
    import fn_check_ltcg as L

    units = load_units() if units is None else units
    if not units:
        return {}
    symbols = load_symbols(symbols_txt)
    out = {}
    for unit in units:
        source = unit["source"]
        split = split_object(split_dir, source)
        if not split.is_file():
            raise SystemExit(f"missing split object for LTCG unit {source}: {split}")
        coff = read_coff(split)
        sizes = unit["symbols"]

        def find_target(name, coff=coff):
            code, relocs = coff.function(name, sizes[name])
            address = next(e[2] for e in symbols if e[0] == name)
            return address, code, relocs

        pairs = [(name, name) for name in sizes]
        kwargs = {"toolchain": toolchain, "wibo": wibo, "verbose": False}
        if target_image is not None:
            kwargs["target_image"] = target_image
        print(f"+ ltcg {source} ({len(pairs)} function(s), context {unit.get('context', [])})")
        checked, _ci, _ti, workdir = L.verify(
            ROOT / source, [absolute_context(c) for c in unit.get("context", [])],
            unit.get("flags", []), pairs, find_target, symbols,
            no_include=unit.get("no_include", False), extra_includes=unit.get("include", []),
            **kwargs)
        bad = [c for c in checked if c.result is None or not c.result.ok
               or c.result.renames]
        if bad:
            lines = [f"{c.candidate}: " + ("not in linked image" if c.result is None else
                     "; ".join(c.result.problems or [f"unapplied renames {c.result.renames}"]))
                     for c in bad]
            raise SystemExit(f"LTCG unit {source} does not match (scratch {workdir}):\n  "
                             + "\n  ".join(lines))
        functions = []
        for c in checked:
            masks = [0] * (len(c.t_code) // 4)
            for site in c.t_sites:
                masks[site.offset // 4] |= L.MASKS[site.kind]
            functions.append((c.candidate, c.c_code[: len(c.t_code)], masks))
        rebuilt = rebuilt_dir / unit["object"]
        rebuilt.parent.mkdir(parents=True, exist_ok=True)
        rebuilt.write_bytes(patch_object(split.read_bytes(), functions))
        out[source] = rebuilt
    return out


def absolute_context(entry: str) -> str:
    """A context entry (`[nogl:][flags(...):]path`) with its path made absolute."""
    import fn_check_ltcg as L

    mode, flags, path = L.parse_context(entry)
    prefix = ("nogl:" if mode == "nogl" else "") + (f"flags({' '.join(flags)}):" if flags else "")
    return prefix + str(ROOT / path)


def context_paths(units: list[dict] | None = None) -> list[str]:
    units = load_units() if units is None else units
    import fn_check_ltcg as L

    return sorted({str(L.parse_context(c)[2]) for u in units for c in u.get("context", [])})


if __name__ == "__main__":
    for unit in load_units():
        print(unit["source"], len(unit["symbols"]), "function(s)")


# --------------------------------------------------------------------------- hooks for the pipeline
# These keep the edits to tools/matching.py, tools/integrate_match.py,
# tools/sync_progress.py and tools/link_probe.py to a few lines each; the
# exact patch is in docs/ltcg-route.md section 6.

def add_arguments(parser) -> None:
    """Options tools/matching.py needs only when LTCG units exist."""
    parser.add_argument("--ltcg-wibo", type=Path,
                        default=ROOT / "work" / "wibo-src" / "build" / "release64" / "wibo",
                        help="wibo build that runs link.exe (decompals/wibo PR 110)")
    parser.add_argument("--ltcg-toolchain", type=Path, default=ROOT / "work" / "ltcg-toolchain",
                        help="compiler copy with the OLEAUT32 stub (tools/fn_check_ltcg.py --setup)")
    parser.add_argument("--ltcg-target-image", type=Path,
                        default=ROOT / "orig" / "54540859" / "Swing_DLL.dll",
                        help="decompressed PE of the XEX, read for pooled-constant values")


def build(args, rebuilt_dir: Path, split_dir: Path, symbols_txt: Path, _xex: Path) -> dict[str, Path]:
    """tools/matching.py hook: verify LTCG units and return {source: rebuilt object}."""
    units = load_units()
    if not units:
        return {}
    return build_units(rebuilt_dir, split_dir, symbols_txt, args.ltcg_wibo.expanduser().resolve(),
                       args.ltcg_toolchain.expanduser().resolve(),
                       args.ltcg_target_image.expanduser().resolve(), units)


def all_units(plain_units) -> list[dict]:
    """MATCHING_UNITS followed by the LTCG units (same keys: source, object, symbols)."""
    return [*plain_units, *load_units()]


def register(spec: dict, symbol_sizes: dict[str, int], path: Path = UNITS_PATH) -> None:
    """tools/integrate_match.py hook: record a spec with "route": "ltcg"."""
    units = load_units(path)
    if any(u["source"] == spec["source"] for u in units):
        raise SystemExit(f"{spec['source']} is already an LTCG unit")
    import fn_check_ltcg as L

    for entry in spec.get("context", []):
        if not (ROOT / L.parse_context(entry)[2]).is_file():
            raise SystemExit(f"missing context source {entry}")
    unit = {"source": spec["source"], "object": Path(spec["source"]).stem + ".obj",
            "context": spec.get("context", []), "flags": spec.get("flags", []),
            "no_include": bool(spec.get("no_include", False)), "include": spec.get("include", []),
            "symbols": symbol_sizes}
    units.append(unit)
    path.write_text(json.dumps(units, indent=1) + "\n")
