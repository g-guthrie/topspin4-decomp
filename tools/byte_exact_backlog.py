#!/usr/bin/env python3
"""List every EQUIVALENT-tier function as owed a byte-exact match.

Usage: python3 tools/byte_exact_backlog.py [--out reports/byte_exact_backlog.md]

Functions solved on the equivalent route (config/54540859/equivalent.json) are
correct in behaviour but not yet byte-identical. Owner decision (2026-11-22):
that is acceptable for the port, but each one stays on record so it can be
taken to a byte match later. This writes that record.

The "gap" column comes from a comment in the source directly above (or on the
line of) the function definition:

    /* byte-gap: 7 off (perm best 7); LTCG keeps r4 live across the call */

Rows whose source has no such comment show "(not recorded)".
"""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EQUIV = ROOT / "config" / "54540859" / "equivalent.json"
GAP = re.compile(r"byte-gap:\s*(.+?)\s*(?:\*/|$)")


def gap_for(source: Path, function: str) -> str:
    if not source.is_file():
        return "(source missing)"
    lines = source.read_text(errors="replace").splitlines()
    for i, line in enumerate(lines):
        if re.search(rf"\b{re.escape(function)}\s*\(", line) and not line.rstrip().endswith(";"):
            for j in range(i, max(-1, i - 12), -1):
                m = GAP.search(lines[j])
                if m:
                    return m.group(1)
                if j < i and lines[j].strip() == "}":
                    break
            return "(not recorded)"
    return "(definition not found)"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, default=ROOT / "reports" / "byte_exact_backlog.md")
    args = ap.parse_args()
    rows = json.loads(EQUIV.read_text())["rows"]
    rows.sort(key=lambda r: int(r["address"], 16))
    total = sum(r["size"] for r in rows)
    out = [
        "# Byte-exact backlog",
        "",
        "Functions solved on the equivalent route: behaviour proven by tools/fn_equiv.py,",
        "not yet byte-identical. Each is owed a byte match. Generated by",
        "`python3 tools/byte_exact_backlog.py` from config/54540859/equivalent.json.",
        "",
        f"{len(rows)} functions, {total} bytes.",
        "",
        "| Address | Size | Function | Source | Flags | Gap to byte match |",
        "|---|---|---|---|---|---|",
    ]
    for r in rows:
        gap = gap_for(ROOT / r["source"], r["function"])
        out.append(f"| {r['address']} | {r['size']} | `{r['function']}` | `{r['source']}` | "
                   f"{' '.join(r.get('spec_flags') or r.get('flags') or []) or '-'} | {gap} |")
    args.out.write_text("\n".join(out) + "\n")
    print(f"wrote {args.out.relative_to(ROOT)}: {len(rows)} functions, {total} bytes")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
